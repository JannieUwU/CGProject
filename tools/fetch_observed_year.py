"""Refresh bundled Horizons states; runtime and tests are fully offline.

Run from the repository root with Python 3. Uses only the standard library.
"""
import csv
import datetime as dt
import json
import sys
from pathlib import Path
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'ephemeris-year'
OUT.mkdir(parents=True, exist_ok=True)
DATES = ['2025-11-28', '2026-02-28', '2026-05-28', '2026-08-28', '2026-11-28']
JD = [2451544.5 + (dt.date.fromisoformat(s) - dt.date(2000, 1, 1)).days for s in DATES]
IDS = [10, 1, 2, 3, 4, 5, 6, 7, 8]
NAMES = ['sun', 'mercury', 'venus', 'earth', 'mars', 'jupiter', 'saturn', 'uranus', 'neptune']
# JPL astro_par.html, DE440 GM in km^3/s^2. Earth includes Moon.
GM = [132712440041.279419, 22031.868551, 324858.592000,
      398600.435507 + 4902.800118, 42828.375816, 126712764.100000,
      37940584.841800, 5794556.400000, 6836527.100580]
# Nominal physical radii in km; display radii are independent.
RADII = [695700, 2439.4, 6051.8, 6371, 3389.5, 69911, 58232, 25362, 24622]
records = []
for code, name in zip(IDS, NAMES):
    params = dict(format='json', COMMAND=f"'{code}'", EPHEM_TYPE="'VECTORS'",
                  CENTER="'500@0'", REF_PLANE="'ECLIPTIC'", REF_SYSTEM="'ICRF'",
                  OUT_UNITS="'AU-D'", VEC_TABLE="'2'", CSV_FORMAT="'YES'",
                  VEC_CORR="'NONE'", TLIST="'" + ','.join(map(str, JD)) + "'")
    url = 'https://ssd.jpl.nasa.gov/api/horizons.api?' + urllib.parse.urlencode(params)
    if '--offline' in sys.argv:
        result = (OUT / f'horizons-{code}.txt').read_text(encoding='utf-8')
    else:
        payload = json.load(urllib.request.urlopen(url, timeout=90))
        result = payload.get('result', '')
    if '$$SOE' not in result:
        raise RuntimeError('Horizons response contains no state vectors')
    (OUT / f'horizons-{code}.txt').write_text(result, encoding='utf-8')
    rows = list(csv.reader(result.split('$$SOE')[1].split('$$EOE')[0].strip().splitlines()))
    if len(rows) != len(JD):
        raise RuntimeError('Incomplete Horizons result')
    states = []
    for expected_jd, row in zip(JD, rows):
        if float(row[0]) != expected_jd:
            raise RuntimeError('Epoch mismatch')
        states.append([float(value) for value in row[2:8]])
    records.append(dict(id=name, horizons_id=code, url=url, states=states))
    print(name, 'downloaded')
data = dict(dates_tdb=DATES, jd_tdb=JD, frame='J2000 ecliptic / solar-system barycenter',
            units='AU, day, solar mass', gm_km3_s2=GM, physical_radii_km=RADII, bodies=records)
(OUT / 'states.json').write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
lines = ['// Generated by tools/fetch_observed_year.py. Source: NASA/JPL Horizons.',
         f'constexpr double observed_epoch_jd = {JD[0]};',
         'constexpr double observed_states[9][8] = {']
for gm, radius, record in zip(GM, RADII, records):
    values = [gm / GM[0], radius / 149597870.7] + record['states'][0]
    lines.append('    {' + ', '.join(format(v, '.17g') for v in values) + '}, // ' + record['id'])
lines += ['};', 'constexpr double observed_reference_days[5] = {' + ', '.join(str(j-JD[0]) for j in JD) + '};',
          'constexpr double observed_reference_positions[5][9][3] = {']
for day in range(len(JD)):
    lines.append('    {')
    for record in records:
        lines.append('        {' + ', '.join(format(v, '.17g') for v in record['states'][day][:3]) + '},')
    lines.append('    },')
lines += ['};', '']
(ROOT / 'src' / 'observed_year_data.inc').write_text('\n'.join(lines), encoding='utf-8')
display_radii = [.12, .055, .065, .07, .06, .18, .16, .11, .105]
project = dict(type='solar-system', view_extent=34.0, display_scale=1.0,
               epoch_jd=JD[0], duration_days=365.0,
               gravitational_constant=GM[0]*86400**2/149597870.7**3, bodies=[])
for record, gm, radius, display in zip(records, GM, RADII, display_radii):
    project['bodies'].append(dict(id=record['id'], name=record['id'].capitalize(), kind=record['id'],
                                 mass=gm/GM[0], radius=radius/149597870.7, display_radius=display,
                                 position=record['states'][0][:3], velocity=record['states'][0][3:]))
(ROOT / 'examples' / 'observed-year.json').write_text(json.dumps(project, indent=2)+'\n', encoding='utf-8')
